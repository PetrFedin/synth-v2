BEGIN;

-- Когда событие встало в очередь.
--
-- У `outbox_events` не было **ни одной** собственной отметки времени, кроме `published_at`, который
-- заполняется только после доставки. Возраст неотправленного события можно было узнать лишь разбором
-- `event->>'occurredAt'` — то есть доменного времени из полезной нагрузки, по случайности совпадающего
-- с временем постановки, потому что outbox пишется в той же транзакции, что и сама запись. Полагаться
-- на совпадение нельзя: событие, у которого нет `occurredAt`, становится бессрочным, а вопрос «сколько
-- ждёт самое старое» — единственный, который вообще говорит, жива очередь или нет.
--
-- Отсюда и молчание, которое нашёл аудит: 1067 событий ждали больше месяца, и ни один запрос не мог
-- ответить об этом дёшево — ни проверка готовности, ни обслуживание, ни человек в psql.
ALTER TABLE outbox_events
  ADD COLUMN IF NOT EXISTS queued_at timestamptz;

-- Засев точный, а не приблизительный: у всех существующих строк `occurredAt` есть, и это ровно то
-- время, когда запись и событие были записаны одной транзакцией. `now()` здесь означал бы «мы не
-- знаем» и стёр бы именно тот факт, ради которого колонка заводится, — что событие старое.
UPDATE outbox_events
   SET queued_at = COALESCE((event->>'occurredAt')::timestamptz, published_at, now())
 WHERE queued_at IS NULL;

ALTER TABLE outbox_events
  ALTER COLUMN queued_at SET DEFAULT now();
ALTER TABLE outbox_events
  ALTER COLUMN queued_at SET NOT NULL;

-- Вопрос у очереди ровно один и всегда один и тот же: сколько ждущих и как давно ждёт старейшее.
-- Частичный индекс отвечает на него, не читая доставленные, которых со временем становится больше всех.
CREATE INDEX IF NOT EXISTS outbox_pending_queued_at_idx
  ON outbox_events (queued_at)
  WHERE status = 'pending';

COMMIT;
