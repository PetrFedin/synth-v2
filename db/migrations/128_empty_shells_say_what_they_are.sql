BEGIN;

-- Три пустые таблицы объясняют себя сами.
--
-- Аудит назвал их «пустыми скорлупами». Разбор показал, что это три разные вещи, и одинаковое
-- решение по ним было бы неверным. Общее у них одно: ни одна не могла сказать о себе, почему она
-- пуста, а таблица без строк и без объяснения читается как недоделка независимо от того, чем она
-- является на самом деле. Комментарий стоит там, где читатель на неё наткнётся — в `\d+`.

-- 1. Палитра сезона — **достроена** в этом же изменении: у неё появились домен, хранилище, служба и
-- маршруты, а демонстрация собирает её из тех же цветов справочника, которыми покрашено полотно.
COMMENT ON TABLE season_colour_palettes IS
  'Палитра сезона: цвета, которыми сезону разрешено рисовать, закреплённые версией записи справочника. Ведётся через POST /v2/campaigns/{id}/palette, читается через GET того же адреса. Версия закрепляется потому, что палитра — решение, принятое один раз: переименование оттенка в справочнике не должно менять утверждённый сезон.';

-- 2. Перечень операций техпакета — **вытеснен**, а не продублирован. Миграция 089 привязывала
-- операции к самому техпакету; миграция 116 завела отдельную последовательность (`bol_sequences`)
-- с этапом и узлом конструкции, и работа идёт через неё: 20 строк против нуля. Слить их нельзя —
-- это разные агрегаты с разными ключами, и «объединение» снесло бы класс оборудования, которого во
-- второй модели нет.
COMMENT ON TABLE tech_pack_operations IS
  'ВЫТЕСНЕНА последовательностью операций (bol_sequences / bol_operations, миграция 116): там есть этап и узел конструкции, и работа идёт через неё. Таблица сохранена, потому что несёт класс оборудования, которого во второй модели нет, и может понадобиться при переносе. Писателя нет; ноль строк — это не недоделка.';

-- 3. Исходящая очередь каталога — **отставной путь записи**. Ни одной вставки в неё нет ни в `src/`,
-- ни в миграциях: каталог пишет события прямо в единую `outbox_events`. Зеркалирующий триггер,
-- счётчик метрики и уборка оставлены совместимостью на случай, если старый писатель где-то ещё жив.
COMMENT ON TABLE catalog_outbox_events IS
  'ОТСТАВНОЙ путь записи: события каталога идут прямо в outbox_events. Вставок нет нигде в коде; зеркалирующий триггер, счётчик метрики и уборка оставлены совместимостью. Ноль строк — ожидаемое состояние, а не потерянные события.';

COMMIT;
