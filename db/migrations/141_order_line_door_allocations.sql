BEGIN;

-- Распределение заказа по точкам розницы (docs/backlog-not-yet-integrated.md, раздел 5 P1:
-- «распределение по магазинам и дверям (`retail_doors` есть, распределения нет)»). Точки розницы
-- (миграция 057) и их реестр в интерфейсе (`feat/retail-door-registry-ui`) уже построены; заказ же
-- по-прежнему закрепляется максимум за ОДНОЙ дверью целиком (`orders.retail_door_id`, необязательное
-- поле коммерчески закреплённого заказа) — распределить одну строку заказа между несколькими дверями
-- одного магазина было нечем.
--
-- Это НЕ то же самое, что отклонённая идея «количеств по каналам»: канал (свой магазин / маркетплейс
-- / e-com) — категория бизнес-модели, которой в проекте нет вовсе ни как понятия, ни как таблицы;
-- дверь — уже существующая, физическая точка продаж конкретного магазина с собственным реестром.
--
-- Маленькая изменяемая таблица, а не правка заказа: `orders.payload`/`order_commit_snapshots.payload`
-- неизменяемы, а распределение по дверям — операционное решение магазина, которое может уточняться
-- уже после того, как заказ подтверждён, а не часть коммерческого предмета сделки. Отсутствие строки
-- значит «не распределено» — по умолчанию всё уходит в закреплённую дверь заказа, если она есть, или
-- никуда конкретно, если нет; строка не журнал, новая запись на ту же дверь полностью замещает
-- прежнее количество, а не добавляется к нему.
--
-- Это информационное распределение, а не команда на исполнение: оно не разбивает план отгрузки и
-- не трогает механику `fulfillment_plan_snapshots`/резервирования склада — магазин фиксирует замысел,
-- по какой двери сколько единиц строки должно разойтись, а не то, как это физически будет отгружено.
CREATE TABLE order_line_door_allocations (
  order_id text NOT NULL,
  line_no integer NOT NULL CHECK (line_no > 0),
  retail_door_id text NOT NULL REFERENCES retail_doors(id),
  quantity integer NOT NULL CHECK (quantity > 0),
  updated_at timestamptz NOT NULL,
  updated_by text NOT NULL,
  PRIMARY KEY (order_id, line_no, retail_door_id)
);

CREATE INDEX order_line_door_allocations_order_idx ON order_line_door_allocations (order_id);
CREATE INDEX order_line_door_allocations_door_idx ON order_line_door_allocations (retail_door_id);

COMMENT ON TABLE order_line_door_allocations IS
  'Распределение одной строки заказа по точкам розницы магазина. Одна запись на дверь на строку, новая замещает прежнюю; отсутствие строки значит «не распределено». Информационное намерение магазина, не часть механики отгрузки/резервирования.';

COMMIT;
