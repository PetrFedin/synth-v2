BEGIN;

-- GTIN идентифицирует торговую единицу глобально: один и тот же код на двух SKU означает, что
-- сканер, маркировка и EDI-партнёр увидят два изделия под одним штрихкодом. Проверка контрольной
-- цифры живёт в домене (проверять её в CHECK значило бы отвергнуть уже записанные строки), а
-- уникальность — здесь, чтобы гонка двух команд не обошла проверку приложения. Если миграция
-- падает на дубликатах, их надо разобрать вручную: молча выбрать «правильный» SKU нельзя.
CREATE UNIQUE INDEX product_skus_gtin_unique
  ON product_skus (gtin)
  WHERE gtin IS NOT NULL;

COMMIT;
