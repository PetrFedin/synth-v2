// Что видит в реестре материалов тот, кому себестоимость не положена.
//
// Себестоимость полотна — это закупочная цена у поставщика, и модель прав уже говорит, кому она
// принадлежит: `COST_MANAGE` есть у владельца, администратора и финансов, `MARGIN_READ` — у
// продаж и финансов, а у роли `viewer` денежных способностей нет **ни одной**. Реестры, где
// себестоимость и есть предмет — ведомость, целевое ценообразование, экономика сезона, платежи
// поставщику — читаются ровно владельцем, администратором и финансами.
//
// Реестр материалов эту модель не спрашивал. Проверено живьём: `viewer` получал из
// `GET /v2/materials` строку с `unitCost`, то есть закупочную цену, — и тот же `viewer` получал
// **ноль строк** из `GET /v2/boms`, где та же цена лежит в составе изделия. Один и тот же факт
// охранялся в одном месте и был открыт в другом.
//
// Закрывать материал целиком нельзя и не нужно: продажам и производству надо знать название,
// цвет, единицу, состав и остаток — без этого не работают. Поэтому изымается **поле**, а не
// строка, тем же приёмом, каким из каталога изымаются внутренние складские числа
// (`catalog-counterparty-projection.mjs`). Разница ровно одна: там признак — чужая организация,
// здесь — роль без права на себестоимость.
//
// Цена без валюты — это не цена, а число, поэтому валюта уходит вместе с ней: половина факта
// хуже его отсутствия, потому что выглядит как целый факт.
const COST_FIELDS = Object.freeze(['unitCost', 'currency']);

// Те же роли, какими читаются реестры, где себестоимость и есть предмет.
export const MATERIAL_COST_READ_ROLES = Object.freeze(['owner', 'admin', 'finance']);

export function roleReadsMaterialCost(role) {
  return typeof role === 'string' && MATERIAL_COST_READ_ROLES.includes(role);
}

/**
 * Убрать себестоимость из строки материала, если роль читателя на неё не имеет права.
 *
 * Роль приходит из членства, прочитанного тем же запросом: спрашивать её отдельно значило бы
 * прочитать права в один момент, а материал в другой.
 */
export function projectMaterialForRole(payload, role) {
  if (!payload || typeof payload !== 'object') return payload;
  if (roleReadsMaterialCost(role)) return payload;
  const projected = { ...payload };
  for (const field of COST_FIELDS) delete projected[field];
  return Object.freeze(projected);
}
